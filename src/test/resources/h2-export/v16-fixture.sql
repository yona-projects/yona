CREATE TABLE N4USER (ID BIGINT NOT NULL PRIMARY KEY, LOGIN_ID VARCHAR(255), NAME VARCHAR(255), IS_GUEST BOOLEAN, CREATED_DATE TIMESTAMP, STATE INTEGER, TOKEN VARCHAR(255));
CREATE SEQUENCE N4USER_SEQ START WITH 100;
CREATE TABLE ISSUE (ID BIGINT NOT NULL PRIMARY KEY, TITLE VARCHAR(255), BODY CLOB, STATE TINYINT, LEVEL_NO SMALLINT, MILESTONE_ID BIGINT, DUE_DATE DATE);
CREATE SEQUENCE ISSUE_SEQ;
CREATE TABLE ISSUE_VOTER (ISSUE_ID BIGINT NOT NULL, USER_ID BIGINT NOT NULL);
CREATE TABLE EMPTY_THING (ID BIGINT NOT NULL PRIMARY KEY, NOTE VARCHAR(10));
CREATE SEQUENCE EMPTY_THING_SEQ;

